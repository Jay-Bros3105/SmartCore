type LangCtx = {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: (key: string, vars?: Record<string, string | number>) => string;
};

const Ctx = createContext<LangCtx>({ lang: 'en', setLang: () => {}, t: (k) => k });

export function LanguageProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLang] = useState<Lang>('en');

  useEffect(() => {
    const saved = typeof window !== 'undefined' ? localStorage.getItem('neo_admin_lang') : null;
    if (saved === 'sw' || saved === 'en') setLang(saved);
  }, []);

  const apply = (l: Lang) => {
    setLang(l);
    if (typeof window !== 'undefined') localStorage.setItem('neo_admin_lang', l);
  };

  const t = (key: string, vars?: Record<string, string | number>): string => {
    let s = dict[lang][key] ?? dict.en[key] ?? key;
    if (vars) {
      for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v));
    }
    return s;
  };

  return <Ctx.Provider value={{ lang, setLang: apply, t }}>{children}</Ctx.Provider>;
}

export const useLang = () => useContext(Ctx);